#!/usr/bin/env python3
"""
Convert MAVLink C headers into Cyphal DSDL messages,
auto-adding @extent and sanitizing reserved names.
Supports multiple MAVLink directories (e.g., common, lisum) and
generates each in its own subfolder.
"""

from __future__ import annotations
import argparse
import pathlib
import re
import shutil
import sys
from dataclasses import dataclass

# Map C types to Cyphal DSDL types
PRIMITIVE_MAP = {
    'uint8_t': 'saturated uint8',
    'int8_t': 'saturated int8',
    'uint16_t': 'saturated uint16',
    'int16_t': 'saturated int16',
    'uint32_t': 'saturated uint32',
    'int32_t': 'saturated int32',
    'uint64_t': 'saturated uint64',
    'int64_t': 'saturated int64',
    'float': 'float32',
    'double': 'float64',
    'char': 'saturated uint8',  # arrays only
}

SUBJECT_ID_OFFSET = 10000
RESERVED_NAMES = {"type", "class", "package", "import"}  # dodaj po potrebi

STRUCT_REGEX = re.compile(
    r"typedef struct __mavlink_(?P<name>[a-zA-Z0-9_]+)_t \{(?P<body>.*?)\} mavlink_\1_t;",
    re.DOTALL
)
FIELD_REGEX = re.compile(
    r"^(?P<type>[a-z0-9_]+)(?:\s+(?P<name>[a-z0-9_]+))(?:\[(?P<len>\d+)\])?;.*$",
    re.IGNORECASE
)
MSG_ID_REGEX = re.compile(r"#define MAVLINK_MSG_ID_(?P<name>[A-Z0-9_]+)\s+(?P<id>\d+)")
LEN_REGEX = re.compile(r"#define MAVLINK_MSG_ID_(?P<name>[A-Z0-9_]+)_LEN\s+(?P<len>\d+)")

@dataclass
class Field:
    dsdl_type: str
    name: str
    array_len: int | None = None

@dataclass
class Message:
    name: str
    struct_name: str
    msg_id: int
    payload_len: int | None
    fields: list[Field]

def sanitize_name(name: str) -> str:
    if name in RESERVED_NAMES:
        return name + "_"
    return name

def camel_case(name_uc: str) -> str:
    parts = name_uc.lower().split('_')
    return ''.join(p.capitalize() for p in parts)

def parse_message_header(text: str) -> Message | None:
    msgid_match = MSG_ID_REGEX.search(text)
    if not msgid_match:
        return None
    name_uc = msgid_match.group('name')
    msg_id = int(msgid_match.group('id'))
    len_match = LEN_REGEX.search(text)
    payload_len = int(len_match.group('len')) if len_match else None

    struct_match = STRUCT_REGEX.search(text)
    if not struct_match:
        return None
    struct_body = struct_match.group('body')
    struct_name = struct_match.group('name')

    fields: list[Field] = []
    for line in struct_body.splitlines():
        line = line.strip()
        if not line or line.startswith('//'):
            continue
        m = FIELD_REGEX.match(line)
        if not m:
            continue
        c_type = m.group('type')
        fname = sanitize_name(m.group('name'))
        arrlen = m.group('len')
        if c_type not in PRIMITIVE_MAP:
            continue
        base = PRIMITIVE_MAP[c_type]
        array_len = int(arrlen) if arrlen else None
        fields.append(Field(base, fname, array_len))

    return Message(name_uc, struct_name, msg_id, payload_len, fields)

def generate_dsdl(message: Message, dialect: str, override_subject_id: int | None = None) -> tuple[str, int]:
    subject_id = override_subject_id if override_subject_id is not None else message.msg_id

    # Keep human-readable comments for traceability. Fixed port-ID is conveyed via filename prefix.
    lines = [
        f"# Autogenerated from MAVLink message {message.name}",
        f"# Original MAVLink ID: {message.msg_id}",
        f"# Dialect: {dialect}",
        "",
    ]
    for f in message.fields:
        if f.array_len is not None:
            lines.append(f"{f.dsdl_type}[{f.array_len}] {f.name}")
        else:
            lines.append(f"{f.dsdl_type} {f.name}")
    lines.append("")
    max_extent_bytes = message.payload_len or 256
    lines.append(f"@extent {max_extent_bytes * 8}")  # bitovi
    # Do not emit @fixed_port_id: current pydsdl reports Unknown directive.
    # Fixed port-ID is conveyed via numeric filename prefix (e.g., 600.Name.1.0.dsdl).
    lines.append("")

    return '\n'.join(lines), subject_id


def main() -> int:
    ap = argparse.ArgumentParser(description="Convert MAVLink headers to Cyphal DSDL.")
    ap.add_argument(
        '--mavlink-dirs', 
        nargs='+', 
        required=True, 
        help="List of MAVLink C header directories (e.g., common lisum)"
    )
    ap.add_argument('--out-dir', required=True, help="Output root directory for DSDL files")
    ap.add_argument('--emit-reg-publishers', action='store_true', help="Also emit reg.udral publishers helpers")
    args = ap.parse_args()

    out_dir = pathlib.Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    generated = 0

    # Root namespace prefix (no 'mavlink' token) with per-dialect subfolders (e.g., common, lisum)
    root_ns = out_dir / "messages_cyphal_uavcan"
    if root_ns.exists():
        shutil.rmtree(root_ns)
    root_ns.mkdir(parents=True, exist_ok=True)

    MAX_REGULATED_FIXED_SUBJECT_ID = 8191  # pydsdl restricts fixed IDs to regulated range unless directive supported

    for mav_dir in map(pathlib.Path, args.mavlink_dirs):
        if not mav_dir.is_dir():
            print(f"MAVLink dir not found: {mav_dir}", file=sys.stderr)
            continue

        dialect_name = mav_dir.name  # used for metadata and directory separation
        dialect_ns = root_ns / dialect_name
        dialect_ns.mkdir(parents=True, exist_ok=True)

        headers = sorted(mav_dir.glob('mavlink_msg_*.h'))
        if not headers:
            print(f"No MAVLink message headers found in {mav_dir}", file=sys.stderr)
            continue

        # For lisum dialect, assign fixed port-IDs starting from 600, incrementing per message.
        lisum_base = 600
        lisum_counter = 0
        for hdr in headers:
            text = hdr.read_text(encoding='utf-8', errors='ignore')
            msg = parse_message_header(text)
            if not msg:
                continue
            override_id = None
            if dialect_name.lower() == 'lisum':
                override_id = lisum_base + lisum_counter
                lisum_counter += 1
            dsdl_content, subject_id = generate_dsdl(msg, dialect_name, override_subject_id=override_id)
            # For IDs within regulated range, encode fixed ID via numeric filename prefix.
            # For larger IDs, omit the prefix to avoid pydsdl InvalidFixedPortIDError; we will still publish to
            # the MAVLink ID via helper wrappers.
            if subject_id <= MAX_REGULATED_FIXED_SUBJECT_ID:
                fname = f"{subject_id}.{camel_case(msg.name)}.1.0.dsdl"
            else:
                fname = f"{camel_case(msg.name)}.1.0.dsdl"
            (dialect_ns / fname).write_text(dsdl_content, encoding='utf-8')
            generated += 1

    # Optionally emit reg.udral publishers helpers into build/cyphal/utility
    if args.emit_reg_publishers:
        util_dir = out_dir / "utility"
        util_dir.mkdir(parents=True, exist_ok=True)

        reg_h = util_dir / "cyphal_reg_publishers.h"
        reg_c = util_dir / "cyphal_reg_publishers.c"

        reg_h.write_text(
            """#ifndef CYPHAL_REG_PUBLISHERS_H\n#define CYPHAL_REG_PUBLISHERS_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n#include \"canard.h\"\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n// Publish reg.udral.physics.thermodynamics.PressureTempVarTs.0.1 message\nint cyphal_publish_reg_pressure_temp_var_ts(\n    struct CanardInstance* ins,\n    struct CanardTxQueue* txq,\n    enum CanardPriority prio,\n    const void* payload,\n    size_t payload_size,\n    CanardTransferID* tid,\n    CanardMicrosecond timeout_usec);\n\n#ifdef __cplusplus\n}\n#endif\n\n#endif // CYPHAL_REG_PUBLISHERS_H\n""",
            encoding='utf-8',
        )

        reg_c.write_text(
            """/* Auto-generated Cyphal reg.udral publish helpers. */\n#include \"cyphal_utility.h\"\n#include \"canard.h\"\n#include <string.h>\n\n#include \"messages/reg/udral/physics/thermodynamics/PressureTempVarTs_0_1.h\"\n\nint cyphal_publish_reg_pressure_temp_var_ts(struct CanardInstance* ins, struct CanardTxQueue* txq, enum CanardPriority prio, const void* payload, size_t payload_size, CanardTransferID* tid, CanardMicrosecond timeout_usec) {\n    return cyphal_pub_message(ins, txq, reg_udral_physics_thermodynamics_PressureTempVarTs_0_1_FIXED_PORT_ID_, prio, payload, payload_size, tid, timeout_usec);\n}\n""",
            encoding='utf-8',
        )

        print(f"Generated reg.udral publishers into {util_dir}")

    print(f"Generated {generated} DSDL files into {out_dir}")
    return 0

if __name__ == '__main__':
    sys.exit(main())
